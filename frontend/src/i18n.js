export const STRINGS = { ko, en, zh, vi };

export function makeT(lang) {
  const table = STRINGS[lang] ?? ko;
  return (key, vars = {}) => {
    const value = table[key] ?? ko[key] ?? key;
    if (typeof value !== "string") return value; // examples·log.flow 같은 목록
    return value.replace(/\{([\w+]+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
  };
}

// 번역본 언어 이름을 화면 언어로 (예: 화면이 한국어면 vi → 베트남어)
export function languageName(code, lang) {
  try {
    return new Intl.DisplayNames([lang], { type: "language" }).of(code) ?? code;
  } catch {
    return code;
  }
}

export const I18nContext = createContext({ lang: "ko", t: makeT("ko") });
export const useI18n = () => useContext(I18nContext);
